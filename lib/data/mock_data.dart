Restaurant restaurantById(String id) {
  return restaurants.firstWhere((restaurant) => restaurant.id == id);
}

List<MenuItem> popularItemsFor(Restaurant restaurant) {
  final popular = restaurant.menu.where((item) => item.popular).toList();
  return popular.isEmpty ? restaurant.menu.take(4).toList() : popular;
}

List<MenuItem> menuForCategory(Restaurant restaurant, String category) {
  if (category == 'popular') return popularItemsFor(restaurant);
  return restaurant.menu.where((item) => item.category == category).toList();
}
